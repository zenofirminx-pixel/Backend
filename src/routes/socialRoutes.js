import { Router } from 'express';
import { z } from 'zod';
import { validateBody } from '../middleware/validate.js';
import { requireCsrf } from '../middleware/csrf.js';
import * as controller from '../controllers/socialController.js';
const router = Router();
const postSchema = z.object({ text: z.string().max(5000).optional().default(''), photoData: z.string().max(620000).nullable().optional(), photoMimeType: z.enum(['image/jpeg', 'image/png', 'image/webp']).nullable().optional() }).strict();
const commentSchema = z.object({ text: z.string().trim().min(1).max(2000) }).strict();
const messageSchema = z.object({ text: z.string().trim().min(1).max(4000) }).strict();
const reportSchema = z.object({ targetType: z.enum(['user', 'post', 'comment', 'message']), targetId: z.string().min(1).max(160), reason: z.enum(['spam', 'harassment', 'inappropriate', 'impersonation', 'other']), details: z.string().max(1000).optional().default('') }).strict();
router.get('/feed', controller.feed);
router.post('/posts', requireCsrf, validateBody(postSchema), controller.createPost);
router.delete('/posts/:postId', requireCsrf, controller.deletePost);
router.post('/posts/:postId/like', requireCsrf, controller.likePost);
router.get('/posts/:postId/comments', controller.getComments);
router.post('/posts/:postId/comments', requireCsrf, validateBody(commentSchema), controller.postComment);
router.get('/users/search', controller.search);
router.post('/reports', requireCsrf, validateBody(reportSchema), controller.report);
router.get('/blocks', controller.blocked);
router.post('/users/:uid/block', requireCsrf, controller.block);
router.delete('/users/:uid/block', requireCsrf, controller.unblock);
router.get('/users/:uid', controller.publicProfile);
router.get('/friends', controller.friends);
router.get('/friends/requests', controller.friendRequests);
router.post('/friends/:uid/request', requireCsrf, controller.requestFriend);
router.post('/friends/:uid/accept', requireCsrf, controller.acceptFriend);
router.post('/friends/:uid/decline', requireCsrf, controller.declineFriend);
router.delete('/friends/:uid', requireCsrf, controller.removeFriend);
router.get('/conversations', controller.conversations);
router.get('/messages/:uid', controller.messages);
router.post('/messages/:uid', requireCsrf, validateBody(messageSchema), controller.sendMessage);
router.get('/notifications', controller.notifications);
router.patch('/notifications/:notificationId/read', requireCsrf, controller.markNotification);
export default router;
